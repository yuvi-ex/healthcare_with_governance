-- Every ticket and where it stands. Only decisions by a data owner of the requested branch, who is not the requester, count.
CREATE OR REPLACE VIEW HEALTH_ITSM.TICKET_STATE AS
WITH d AS (
  SELECT d.REQ_NO, d.DECISION, d.DECIDED_BY, d.DECIDED_AT, d.VALID_UNTIL, d.NOTE,
         ROW_NUMBER() OVER (PARTITION BY d.REQ_NO, CASE WHEN d.DECISION = 'APPROVE' THEN 1 ELSE 2 END ORDER BY d.DEC_NO) AS RN
  FROM HEALTH_ITSM.DECISIONS d
  JOIN HEALTH_ITSM.REQUESTS r ON r.REQ_NO = d.REQ_NO
  JOIN HEALTH_ITSM.DATA_OWNERS o ON o.USER_NAME = d.DECIDED_BY AND o.BRANCH = r.BRANCH
  WHERE d.DECIDED_BY <> r.REQUESTER),
a AS (SELECT * FROM d WHERE RN = 1 AND DECISION = 'APPROVE'),
x AS (SELECT * FROM d WHERE RN = 1 AND DECISION IN ('REJECT', 'REVOKE'))
SELECT r.REQ_NO, 'REQ' || LPAD(TO_CHAR(r.REQ_NO), 7, '0') AS TICKET, r.REQUESTER, r.UNIFIED_ID, r.BRANCH, r.REASON,
       r.MINUTES_REQUESTED, r.CREATED_AT, a.DECIDED_BY AS APPROVED_BY, a.DECIDED_AT AS APPROVED_AT, a.VALID_UNTIL,
       x.DECISION AS CLOSED_AS, x.DECIDED_BY AS CLOSED_BY, x.DECIDED_AT AS CLOSED_AT, COALESCE(x.NOTE, a.NOTE) AS NOTE,
       CASE WHEN x.DECISION = 'REJECT' THEN 'REJECTED'
            WHEN x.DECISION = 'REVOKE' THEN 'REVOKED'
            WHEN a.REQ_NO IS NULL THEN 'PENDING'
            WHEN SYSTIMESTAMP >= a.VALID_UNTIL THEN 'EXPIRED'
            ELSE 'ACTIVE' END AS STATUS,
       CASE WHEN x.REQ_NO IS NULL AND a.REQ_NO IS NOT NULL AND SYSTIMESTAMP < a.VALID_UNTIL
            THEN SECONDS_BETWEEN(a.VALID_UNTIL, SYSTIMESTAMP) END AS SECONDS_LEFT
FROM HEALTH_ITSM.REQUESTS r
LEFT JOIN a ON a.REQ_NO = r.REQ_NO
LEFT JOIN x ON x.REQ_NO = r.REQ_NO;

-- ---------------------------------------------------------------- HEALTH_GOV: what a person may read
CREATE SCHEMA IF NOT EXISTS HEALTH_GOV;

-- The access list, evaluated per query for CURRENT_USER: standing access by branch, plus active tickets for one patient's
-- records at one other branch. Not granted to anyone; the views below join to it.
CREATE OR REPLACE VIEW HEALTH_GOV.VISIBLE_RECORDS AS
SELECT m.UNIFIED_ID, r.RECORD_ID, r.BRANCH, r.SOURCE_SYSTEM, CASE WHEN s.PHI_LEVEL = 'FULL' THEN 2 ELSE 1 END AS PHI_RANK,
       CAST(NULL AS VARCHAR(12)) AS TICKET
FROM HOSP_CORE.MPI m JOIN HOSP_CORE.PATIENT_RECORDS r ON r.RECORD_ID = m.RECORD_ID
JOIN HEALTH_ITSM.STANDING_ACCESS s ON s.USER_NAME = CURRENT_USER AND (s.BRANCH = '*' OR s.BRANCH = r.BRANCH)
UNION ALL
SELECT m.UNIFIED_ID, r.RECORD_ID, r.BRANCH, r.SOURCE_SYSTEM, 2, t.TICKET
FROM HOSP_CORE.MPI m JOIN HOSP_CORE.PATIENT_RECORDS r ON r.RECORD_ID = m.RECORD_ID
JOIN HEALTH_ITSM.TICKET_STATE t ON t.REQUESTER = CURRENT_USER AND t.STATUS = 'ACTIVE' AND t.UNIFIED_ID = m.UNIFIED_ID AND t.BRANCH = r.BRANCH;

CREATE OR REPLACE VIEW HEALTH_GOV.VISIBLE AS
SELECT UNIFIED_ID, RECORD_ID, MAX(PHI_RANK) AS PHI_RANK, MAX(TICKET) AS TICKET FROM HEALTH_GOV.VISIBLE_RECORDS GROUP BY UNIFIED_ID, RECORD_ID;

-- One row per person the caller may see at all; a MASKED-only caller gets a pseudonym.
CREATE OR REPLACE VIEW HEALTH_GOV.PERSON AS
SELECT UNIFIED_ID, MAX(PHI_RANK) AS PHI_RANK FROM HEALTH_GOV.VISIBLE GROUP BY UNIFIED_ID;

CREATE OR REPLACE VIEW HEALTH_GOV.MY_ACCESS AS
SELECT 'Standing' AS BASIS, CASE s.BRANCH WHEN '*' THEN 'every branch' ELSE s.BRANCH END AS BRANCH, s.PHI_LEVEL,
       CAST(NULL AS VARCHAR(12)) AS TICKET, CAST(NULL AS VARCHAR(20)) AS UNIFIED_ID, CAST(NULL AS TIMESTAMP) AS VALID_UNTIL,
       CAST(NULL AS DECIMAL(18,0)) AS SECONDS_LEFT
FROM HEALTH_ITSM.STANDING_ACCESS s WHERE s.USER_NAME = CURRENT_USER
UNION ALL
SELECT 'Ticket', t.BRANCH, 'FULL', t.TICKET, t.UNIFIED_ID, t.VALID_UNTIL, t.SECONDS_LEFT
FROM HEALTH_ITSM.TICKET_STATE t WHERE t.REQUESTER = CURRENT_USER AND t.STATUS = 'ACTIVE'
COMMENT IS 'What the caller may see right now and why: standing access by branch (role-based), plus any active ticket, with the seconds it has left.';

CREATE OR REPLACE VIEW HEALTH_GOV.PATIENT_RECORDS AS
SELECT p.UNIFIED_ID,
       CASE WHEN p.PHI_RANK = 2 THEN s.PATIENT_NAME ELSE 'Patient ' || SUBSTR(HASH_SHA1(p.UNIFIED_ID), 1, 6) END AS PATIENT_NAME,
       r.BRANCH, r.SOURCE_SYSTEM,
       CASE WHEN v.RECORD_ID IS NULL THEN 'locked' ELSE 'open' END AS ACCESS,
       CASE WHEN v.PHI_RANK = 2 THEN r.RECORD_ID END AS RECORD_ID,
       v.TICKET
FROM HEALTH_GOV.PERSON p
JOIN HOSP_CORE.PATIENT_SUMMARY s ON s.UNIFIED_ID = p.UNIFIED_ID
JOIN HOSP_CORE.MPI m ON m.UNIFIED_ID = p.UNIFIED_ID
JOIN HOSP_CORE.PATIENT_RECORDS r ON r.RECORD_ID = m.RECORD_ID
LEFT JOIN HEALTH_GOV.VISIBLE v ON v.RECORD_ID = r.RECORD_ID
COMMENT IS 'Grain: one row per record held for a patient the caller may see, in any branch. ACCESS = locked: the record exists (the patient index knows it) but the caller holds no access to it; request a ticket for that BRANCH. RECORD_ID is shown only with full-identity access.';

CREATE OR REPLACE VIEW HEALTH_GOV.ALLERGIES AS
SELECT a.UNIFIED_ID, CASE WHEN v.PHI_RANK = 2 THEN a.RECORD_ID END AS RECORD_ID, r.BRANCH, a.SOURCE_SYSTEM,
       a.ALLERGY_AS_RECORDED, a.DRUG_CLASS, a.SEVERITY, v.TICKET
FROM HOSP_CORE.ALLERGIES a JOIN HEALTH_GOV.VISIBLE v ON v.RECORD_ID = a.RECORD_ID
JOIN HOSP_CORE.PATIENT_RECORDS r ON r.RECORD_ID = a.RECORD_ID
COMMENT IS 'Grain: one row per allergy recorded in any branch system, limited to the records the caller may open. TICKET names the ticket that opened the record (NULL = standing access).';

CREATE OR REPLACE VIEW HEALTH_GOV.ORDERS AS
SELECT o.UNIFIED_ID, CASE WHEN v.PHI_RANK = 2 THEN o.RECORD_ID END AS RECORD_ID, r.BRANCH, o.SOURCE_SYSTEM, o.DRUG, o.DOSE,
       o.ORDER_STATUS, o.DRUG_CLASS
FROM HOSP_CORE.MEDICATIONS o JOIN HEALTH_GOV.VISIBLE v ON v.RECORD_ID = o.RECORD_ID
JOIN HOSP_CORE.PATIENT_RECORDS r ON r.RECORD_ID = o.RECORD_ID
WHERE o.ORDER_STATUS IN ('draft', 'active')
COMMENT IS 'Grain: one row per CURRENT medication order (draft or active), limited to the records the caller may open.';

CREATE OR REPLACE VIEW HEALTH_GOV.ALLERGY_ALERTS AS
SELECT c.UNIFIED_ID,
       CASE WHEN p.PHI_RANK = 2 THEN s.PATIENT_NAME ELSE 'Patient ' || SUBSTR(HASH_SHA1(c.UNIFIED_ID), 1, 6) END AS PATIENT_NAME,
       c.DRUG, c.DOSE, c.ORDER_STATUS, c.DRUG_CLASS, ro.BRANCH AS ORDER_BRANCH, c.ALLERGY_AS_RECORDED, c.SEVERITY,
       ra.BRANCH AS ALLERGY_BRANCH, c.KNOWN_WHERE_PRESCRIBED, va.TICKET
FROM HOSP_CORE.ALLERGY_CONFLICTS c
JOIN HEALTH_GOV.VISIBLE vo ON vo.RECORD_ID = c.PRESCRIBED_UNDER
JOIN HEALTH_GOV.VISIBLE va ON va.RECORD_ID = c.ALLERGY_RECORD_ID
JOIN HEALTH_GOV.PERSON p ON p.UNIFIED_ID = c.UNIFIED_ID
JOIN HOSP_CORE.PATIENT_SUMMARY s ON s.UNIFIED_ID = c.UNIFIED_ID
JOIN HOSP_CORE.PATIENT_RECORDS ro ON ro.RECORD_ID = c.PRESCRIBED_UNDER
JOIN HOSP_CORE.PATIENT_RECORDS ra ON ra.RECORD_ID = c.ALLERGY_RECORD_ID
COMMENT IS 'Certified safety check, governed: a current order whose drug class matches an allergy recorded for the same person, shown only when the caller may open BOTH the order record and the allergy record. With a locked allergy record the alert cannot fire: request a ticket for that branch.';

-- ---------------------------------------------------------------- HEALTH_ITSM views per job
CREATE OR REPLACE VIEW HEALTH_ITSM.MY_REQUESTS AS
SELECT t.TICKET, t.REQ_NO, t.UNIFIED_ID, t.BRANCH, t.REASON, t.MINUTES_REQUESTED, t.CREATED_AT, t.STATUS, t.APPROVED_BY,
       t.APPROVED_AT, t.VALID_UNTIL, t.SECONDS_LEFT, t.CLOSED_AS, t.CLOSED_BY, t.CLOSED_AT, t.NOTE
FROM HEALTH_ITSM.TICKET_STATE t WHERE t.REQUESTER = CURRENT_USER;

-- The data owner's queue: requests for THEIR branch only. Shows who asks and why, not the patient's records.
CREATE OR REPLACE VIEW HEALTH_ITSM.APPROVAL_QUEUE AS
SELECT t.TICKET, t.REQ_NO, t.REQUESTER, p.DISPLAY_NAME AS REQUESTER_NAME, p.JOB AS REQUESTER_JOB, t.UNIFIED_ID, t.BRANCH,
       t.REASON, t.MINUTES_REQUESTED, t.CREATED_AT, t.STATUS, t.APPROVED_AT, t.VALID_UNTIL, t.SECONDS_LEFT, t.CLOSED_AS, t.CLOSED_AT
FROM HEALTH_ITSM.TICKET_STATE t
JOIN HEALTH_ITSM.DATA_OWNERS o ON o.BRANCH = t.BRANCH AND o.USER_NAME = CURRENT_USER
LEFT JOIN HEALTH_ITSM.PEOPLE p ON p.USER_NAME = t.REQUESTER;

CREATE OR REPLACE VIEW HEALTH_ITSM.TICKETS AS
SELECT t.*, p.DISPLAY_NAME AS REQUESTER_NAME FROM HEALTH_ITSM.TICKET_STATE t LEFT JOIN HEALTH_ITSM.PEOPLE p ON p.USER_NAME = t.REQUESTER;

-- Every statement the demo's people ran, with the ticket that was active for them at that moment.
CREATE OR REPLACE VIEW HEALTH_ITSM.AUDIT_TRAIL AS
SELECT s.USER_NAME, p.DISPLAY_NAME, a.START_TIME, a.COMMAND_NAME, a.SUCCESS, a.ERROR_TEXT, ROUND(a.DURATION, 2) AS SECS,
       SUBSTR(a.SQL_TEXT, 1, 160) AS SQL_TEXT, MAX(t.TICKET) AS TICKET
FROM EXA_DBA_AUDIT_SQL a
JOIN EXA_DBA_AUDIT_SESSIONS s ON s.SESSION_ID = a.SESSION_ID
JOIN HEALTH_ITSM.PEOPLE p ON p.USER_NAME = s.USER_NAME
LEFT JOIN HEALTH_ITSM.TICKET_STATE t ON t.REQUESTER = s.USER_NAME AND t.APPROVED_AT IS NOT NULL
      AND a.START_TIME >= t.APPROVED_AT AND a.START_TIME < COALESCE(t.CLOSED_AT, t.VALID_UNTIL)
WHERE a.COMMAND_NAME IN ('SELECT', 'INSERT', 'UPDATE', 'DELETE', 'MERGE', 'NOT SPECIFIED')
  AND a.SQL_TEXT NOT LIKE '/*snapshot execution*/%' AND a.SQL_TEXT NOT LIKE '%EXA_USER_ROLE_PRIVS%'
  AND a.START_TIME >= (SELECT COALESCE(MAX(STARTED_AT), TIMESTAMP '2000-01-01 00:00:00') FROM HEALTH_ITSM.DEMO_EPOCH)
GROUP BY s.USER_NAME, p.DISPLAY_NAME, a.START_TIME, a.COMMAND_NAME, a.SUCCESS, a.ERROR_TEXT, a.DURATION, a.SQL_TEXT, a.SESSION_ID, a.STMT_ID;

