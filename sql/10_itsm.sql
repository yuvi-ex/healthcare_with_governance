-- HEALTH_ITSM: access to patient data is a ticket. A doctor asks, the data owner of the other branch decides, the
-- grant runs out on its own, and every query is on record with the ticket that allowed it.
-- Separate from the existing demo: reads HOSP_CORE (the patient index and the live fused views) and changes nothing there.
--
-- Append-only by design: people INSERT requests and decisions; nobody updates or deletes a ticket. A grant is valid only
-- if the decision came from a data owner of THAT branch who is not the requester, and only until VALID_UNTIL. Those
-- checks live in the views below, so a forged row grants nothing.
CREATE SCHEMA IF NOT EXISTS HEALTH_ITSM;

-- When the demo was last reset (setup/reset.py): the audit trail starts here, so old rehearsals do not crowd it.
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.DEMO_EPOCH (STARTED_AT TIMESTAMP);
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.PEOPLE (USER_NAME VARCHAR(128), DISPLAY_NAME VARCHAR(100), JOB VARCHAR(100));
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.STANDING_ACCESS (USER_NAME VARCHAR(128), BRANCH VARCHAR(3), PHI_LEVEL VARCHAR(6));
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.DATA_OWNERS (USER_NAME VARCHAR(128), BRANCH VARCHAR(3));
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.REQUESTS (
  REQ_NO DECIMAL(18,0) IDENTITY 12340,
  REQUESTER VARCHAR(128),
  UNIFIED_ID VARCHAR(20),
  BRANCH VARCHAR(3),                       -- the branch whose records are requested
  REASON VARCHAR(500),
  MINUTES_REQUESTED DECIMAL(6,0),
  CREATED_AT TIMESTAMP);
CREATE TABLE IF NOT EXISTS HEALTH_ITSM.DECISIONS (
  DEC_NO DECIMAL(18,0) IDENTITY 1,
  REQ_NO DECIMAL(18,0),
  DECISION VARCHAR(8),                     -- APPROVE, REJECT or REVOKE
  DECIDED_BY VARCHAR(128),
  DECIDED_AT TIMESTAMP,
  VALID_UNTIL TIMESTAMP,                   -- APPROVE only
  NOTE VARCHAR(300));

